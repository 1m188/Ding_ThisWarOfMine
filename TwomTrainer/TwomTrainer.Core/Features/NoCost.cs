        new(0x40CF3B, [0x74, 0x05], [0x90, 0x90]),
        new(0x40CF86, [0x75, 0x1A], [0xEB, 0x1A]),

        // 点击「制作」时：可做数 > 0 与可用字节 != 0 两道拒绝判定。
